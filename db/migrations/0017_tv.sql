-- TV providers and their channels, in the database (Ray, 2026-10-21: "the
-- provider selector should appear on all sports... we'll need to have a
-- framework for submitting channels and approving them... database driven
-- rather than spreadsheet").
--
-- Until now these were three spreadsheets that only the Brewers had
-- (data/clubs/mlb/brewers/channel_lookup.csv, provider_lookup.csv,
-- simulcasts.csv). Most of what they said was nobody's club's: a provider's
-- channel for ESPN is the same whoever is playing. So providers, their
-- service areas, networks and channel numbers are one table for every club
-- and sport (Ray chose shared over per club), and the server builds each
-- club's two lookup files from it in the shape the pages already read
-- (lib/tv.js). A network can still be one club's own: Brewers.TV, and the
-- local stations that simulcast the Brewers.
--
-- A provider's areas are named and ordered, as the spreadsheet's "A | B | C"
-- was, and a viewer picks one (Ray chose named areas over ZIP codes). A
-- channel is either for every area of its provider (area NULL) or for one.
--
-- Submissions and their approval come next, writing these same tables.

CREATE TABLE tv_provider (
	id              text PRIMARY KEY CHECK (id ~ '^[a-z0-9_]+$'),
	display_name    text NOT NULL,
	-- Other names a viewer might search for: a provider's parent company, its
	-- former names, the telephone cooperatives it absorbed.
	alternate_names text[] NOT NULL DEFAULT '{}',
	website_url     text,
	lineup_url      text,
	logo_url        text,
	logo_bg         text,
	-- Whether its logo is shown at all; off, it is a name.
	display_logo    boolean NOT NULL DEFAULT FALSE,
	updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE tv_area (
	provider_id text NOT NULL REFERENCES tv_provider (id) ON DELETE CASCADE,
	position    integer NOT NULL CHECK (position >= 0),
	name        text NOT NULL,
	PRIMARY KEY (provider_id, position)
);

CREATE TABLE tv_network (
	id           serial PRIMARY KEY,
	-- The name ESPN gives it in a game's broadcasts, which is how a game finds
	-- it: 'FOX', 'ESPN', 'Brewers.TV'.
	key          text NOT NULL,
	-- NULL for every club's; 'mlb/brewers' for one club's own.
	club         text CHECK (club IS NULL OR club ~ '^[a-z]+/[a-z0-9-]+$'),
	aliases      text[] NOT NULL DEFAULT '{}',
	display_name text NOT NULL,
	kind         text NOT NULL CHECK (kind IN ('broadcast', 'cable', 'regional', 'streaming', 'radio')),
	description  text,
	website_url  text,
	-- The order the lookup file lists networks in.
	position     integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX tv_network_key ON tv_network (key, COALESCE(club, ''));

CREATE TABLE tv_channel (
	provider_id text NOT NULL REFERENCES tv_provider (id) ON DELETE CASCADE,
	network_id  integer NOT NULL REFERENCES tv_network (id) ON DELETE CASCADE,
	-- The provider's area, by position; NULL for every area it has.
	area        integer CHECK (area IS NULL OR area >= 0),
	-- As a lineup prints it: '206', '652 / 1652', '11 (WZAW)'.
	channel     text NOT NULL CHECK (channel <> ''),
	updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX tv_channel_one ON tv_channel (provider_id, network_id, COALESCE(area, -1));

-- Games a club's own channel shares with local over-the-air stations, which
-- no broadcast feed lists; kept by hand from the clubs' announcements.
CREATE TABLE tv_simulcast (
	sport    text NOT NULL,
	club     text NOT NULL,
	date     date NOT NULL,
	channels text NOT NULL,
	note     text,
	PRIMARY KEY (sport, club, date)
);

